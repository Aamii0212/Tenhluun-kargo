-- Тэнхлүүн Карго: захиалсан ачааны урьдчилсан бүртгэл
create table if not exists public.customer_pre_registrations (
  id bigint generated by default as identity primary key,
  customer_phone text not null check (customer_phone ~ '^[0-9]{8}$'),
  tracking_code text not null,
  description text,
  status text not null default 'pending' check (status in ('pending','confirmed','approved','rejected')),
  admin_note text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);


-- Өмнөх хүснэгтэд эдгээр багана/төлөв байгаагүй бол нэмнэ.
alter table public.customer_pre_registrations add column if not exists admin_note text;
alter table public.customer_pre_registrations add column if not exists reviewed_at timestamptz;


-- Хуучин CHECK constraint-ийг шинэ төлөвүүдтэй нийцүүлнэ.
alter table public.customer_pre_registrations drop constraint if exists customer_pre_registrations_status_check;
alter table public.customer_pre_registrations add constraint customer_pre_registrations_status_check check (status in ('pending','confirmed','approved','rejected'));

alter table public.customer_pre_registrations enable row level security;
-- Ижил утас + трак кодоор pending хүсэлтийг давхар үүсгэхээс хамгаална.
create unique index if not exists customer_pre_reg_pending_unique
on public.customer_pre_registrations (customer_phone, lower(trim(tracking_code)))
where status = 'pending';


-- Харилцагч зөвхөн хүсэлт шинээр илгээх эрхтэй
drop policy if exists "public can submit pre registrations" on public.customer_pre_registrations;
create policy "public can submit pre registrations"
on public.customer_pre_registrations for insert
to anon, authenticated
with check (
  customer_phone ~ '^[0-9]{8}$'
  and length(trim(tracking_code)) > 0
  and status = 'pending'
);

-- Урьдчилсан бүртгэлийг зөвхөн admin role-той хэрэглэгч харах/батлах эрхтэй.
drop policy if exists "authenticated can view pre registrations" on public.customer_pre_registrations;
drop policy if exists "authenticated can update pre registrations" on public.customer_pre_registrations;
drop policy if exists cargo_admin_read_pre_registrations on public.customer_pre_registrations;
create policy cargo_admin_read_pre_registrations
on public.customer_pre_registrations for select
to authenticated using (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);
drop policy if exists cargo_admin_update_pre_registrations on public.customer_pre_registrations;
create policy cargo_admin_update_pre_registrations
on public.customer_pre_registrations for update
to authenticated using (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
) with check (
  exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin')
);

grant insert on public.customer_pre_registrations to anon, authenticated;
grant select, update on public.customer_pre_registrations to authenticated;
grant usage, select on sequence public.customer_pre_registrations_id_seq to anon, authenticated;

notify pgrst, 'reload schema';
